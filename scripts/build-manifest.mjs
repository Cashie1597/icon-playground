// Scans the canonical icons/ directory and generates src/icons.generated.ts.
// No external dependencies — pure Node. Run via `npm run icons` (also runs
// automatically before dev/build).
import { readdir, readFile, writeFile, mkdir } from "node:fs/promises";
import { existsSync } from "node:fs";
import { join, dirname, basename, relative } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const iconsDir = join(root, "icons");
const outFile = join(root, "src", "icons.generated.ts");

/** Recursively collect every .svg under a directory. */
async function collect(dir) {
  const out = [];
  if (!existsSync(dir)) return out;
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) out.push(...(await collect(full)));
    else if (entry.isFile() && entry.name.toLowerCase().endsWith(".svg")) out.push(full);
  }
  return out;
}

function slugify(s) {
  return s
    .replace(/\.svg$/i, "")
    .replace(/[^a-zA-Z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .toLowerCase();
}

function titleize(slug) {
  return slug.split("-").map((w) => (w ? w[0].toUpperCase() + w.slice(1) : w)).join(" ");
}

// Extract the inner markup of the first <svg> and its viewBox.
function parseSvg(raw) {
  const open = raw.match(/<svg\b[^>]*>/i);
  if (!open) return null;
  const attrs = open[0];
  const vb = attrs.match(/viewBox\s*=\s*["']([^"']+)["']/i);
  let viewBox = vb ? vb[1] : null;
  if (!viewBox) {
    const w = attrs.match(/\bwidth\s*=\s*["']([\d.]+)/i);
    const h = attrs.match(/\bheight\s*=\s*["']([\d.]+)/i);
    if (w && h) viewBox = `0 0 ${w[1]} ${h[1]}`;
    else viewBox = "0 0 24 24";
  }
  const start = raw.indexOf(open[0]) + open[0].length;
  const end = raw.lastIndexOf("</svg>");
  const body = (end > start ? raw.slice(start, end) : "").trim();
  // Does the icon paint with stroke or fill? Drives default controls.
  const usesStroke = /\bstroke\s*=\s*["'](?!none)/i.test(body) || /\bstroke\s*=\s*["'](?!none)/i.test(attrs);
  return { viewBox, body, usesStroke };
}

async function main() {
  const files = (await collect(iconsDir)).sort();
  const seen = new Set();
  const icons = [];

  for (const file of files) {
    const raw = await readFile(file, "utf8");
    const parsed = parseSvg(raw);
    if (!parsed) continue;
    let slug = slugify(basename(file));
    if (!slug) continue;
    let unique = slug;
    let n = 2;
    while (seen.has(unique)) unique = `${slug}-${n++}`;
    seen.add(unique);
    icons.push({
      slug: unique,
      name: titleize(unique),
      path: relative(root, file),
      viewBox: parsed.viewBox,
      body: parsed.body,
      usesStroke: parsed.usesStroke,
    });
  }

  await mkdir(dirname(outFile), { recursive: true });
  const header =
    "// AUTO-GENERATED by scripts/build-manifest.mjs — do not edit by hand.\n" +
    "// Run `npm run icons` to regenerate from the canonical icons/ directory.\n";
  const type =
    "export type IconDef = {\n" +
    "  slug: string;\n  name: string;\n  path: string;\n  viewBox: string;\n  body: string;\n  usesStroke: boolean;\n};\n\n";
  const data = "export const ICONS: IconDef[] = " + JSON.stringify(icons, null, 2) + ";\n";
  await writeFile(outFile, header + type + data, "utf8");
  console.log(`[icons] wrote ${icons.length} icon(s) -> ${relative(root, outFile)}`);
  if (icons.length === 0) {
    console.warn("[icons] WARNING: no SVGs found in icons/. Add .svg files there.");
  }
}

main().catch((e) => {
  console.error("[icons] failed:", e);
  process.exit(1);
});
